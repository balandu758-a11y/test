#Requires -Version 5.1
<#
.SYNOPSIS
    Air-gapped file transfer over animated QR codes — PowerShell/.NET sender.

.DESCRIPTION
    Wire-compatible re-implementation of glowinthedark's multi-qr-air-gapped-file-transfer
    sender.html (protocol v2). Files are read locally, deflate-raw compressed, split into
    fixed-size blocks, then shown as a paced stream of QR codes: a systematic pass
    (block i verbatim) followed by endless LT/fountain repair packets.

    The packet layout, CRC32, degree distribution and the (sessionId, packetId, k)
    deterministic PRNG are byte-identical to the JavaScript sender, so the original
    receiver.html can decode a transfer produced by this script. Nothing is ever
    uploaded: the only channel is the screen.

    QR symbols are generated by ZXing.Net (NuGet package, vendored under lib\).

.PARAMETER Path
    File to send. If omitted the GUI starts empty and you pick a file / drag one in.

.PARAMETER Preset
    balanced (QR v22, ECC L, 974 B blocks) or robust (QR v15, ECC M, 383 B blocks).

.PARAMETER IntervalMs
    Target milliseconds per QR frame (50..1000). Actual rate is limited by QR build time.

.PARAMETER SessionIdHex
    Override the random 32-bit session id (mainly for tests).

.PARAMETER NoGui
    Headless: print packets/stats to the console (useful on servers, for tests, or piping).

.PARAMETER Frames
    Headless only: stop after N frames (0 = until Ctrl+C).

.PARAMETER DumpPackets
    Headless only: write every generated packet as a .bin file into this directory.

.PARAMETER SelfTest
    Run built-in protocol conformance tests against vectors captured from sender.html
    and exit (0 = pass, 1 = fail).

.EXAMPLE
    .\Send-AirgapQr.ps1 -Path .\secret.pdf

.EXAMPLE
    .\Send-AirgapQr.ps1 -Path .\data.bin -Preset robust -IntervalMs 150

.EXAMPLE
    .\Send-AirgapQr.ps1 -Path .\data.bin -NoGui -Frames 20 -DumpPackets .\out

.EXAMPLE
    .\Send-AirgapQr.ps1 -SelfTest
#>
[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string]$Path,

    [ValidateSet('balanced', 'robust')]
    [string]$Preset = 'balanced',

    [ValidateRange(50, 1000)]
    [int]$IntervalMs = 100,

    [string]$SessionIdHex,

    [switch]$NoGui,

    [int]$Frames = 0,

    [string]$DumpPackets,

    # Headless only: also render each frame to PNG — handy for inspection,
    # printing, or feeding an external QR decoder.
    [string]$DumpQr,

    # Pixels per QR module for -DumpQr (1 = raw module grid, 4 = default).
    [ValidateRange(1, 64)]
    [int]$DumpQrScale = 4,

    [switch]$SelfTest,

    # Defaults to .\lib\ZXing.dll next to this script (downloaded on first run
    # if missing). Kept out of the param block because $PSScriptRoot is not
    # always bound yet while defaults are evaluated under -File.
    [string]$LibPath
)

$ErrorActionPreference = 'Stop'

# =============================================================================
#  Protocol constants (must match sender.html / receiver.html)
# =============================================================================
$script:Presets = @{
    balanced = @{ Version = 22; Ecc = 'L'; Capacity = 1003; Modules = 105; BlockSize = 974 }
    robust   = @{ Version = 15; Ecc = 'M'; Capacity = 412;  Modules = 77;  BlockSize = 383 }
}
$script:DataOverhead = 29      # type+session+pid+k+blockSize+compressed+original+crc
$script:HeaderEvery  = 40      # header frame cadence
$script:U32 = [uint32]

# =============================================================================
#  QR library bootstrap (NuGet package ZXing.Net 0.16.9, lib/net45 build)
#
#  ZXing.Net is used for encoding AND for the self-test's decode oracle. Its QR
#  encoder is the Java reference implementation, so byte-mode payloads at full
#  symbol capacity round-trip exactly (QRCoder 1.4.3 silently zeroes the last
#  few data codewords for zero-heavy packets — see the notes in README.md).
# =============================================================================
function Initialize-QrLib {
    param([string]$Path)

    if (-not (Test-Path -LiteralPath $Path)) {
        Write-Host "ZXing.Net not found at $Path — downloading ZXing.Net 0.16.9 from nuget.org..." -ForegroundColor Yellow
        $dir = Split-Path -Parent $Path
        if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
        $tmp = Join-Path ([IO.Path]::GetTempPath()) ("zxing-" + [Guid]::NewGuid().ToString('N'))
        New-Item -ItemType Directory -Path $tmp -Force | Out-Null
        $nupkg = Join-Path $tmp 'zxing.zip'
        Invoke-WebRequest -Uri 'https://www.nuget.org/api/v2/package/ZXing.Net/0.16.9' -OutFile $nupkg -UseBasicParsing
        Add-Type -AssemblyName System.IO.Compression.FileSystem
        [IO.Compression.ZipFile]::ExtractToDirectory($nupkg, $tmp)
        Copy-Item (Join-Path $tmp 'lib\net45\ZXing.dll') $Path -Force
        Remove-Item $tmp -Recurse -Force -ErrorAction SilentlyContinue
    }

    Add-Type -Path $Path
    Add-Type -AssemblyName System.Numerics
    Add-Type -AssemblyName System.Drawing

    return [pscustomobject]@{
        EccL = [ZXing.QrCode.Internal.ErrorCorrectionLevel]::L
        EccM = [ZXing.QrCode.Internal.ErrorCorrectionLevel]::M
    }
}

# =============================================================================
#  32-bit integer helpers (PowerShell promotes uint32 to wider types on its own,
#  so every operation is explicitly masked back to 32 bits)
# =============================================================================
function Shl32 { param([uint32]$v, [int]$n) [uint32](([uint64]$v -shl $n) -band 4294967295) }
function Shr32 { param([uint32]$v, [int]$n) [uint32](([uint64]$v -shr $n) -band 4294967295) }
function Mul32 { param([uint32]$a, [uint32]$b) [uint32](([uint64]$a * [uint64]$b) -band 4294967295) }
function Xor32 { param([uint32]$a, [uint32]$b) [uint32](([uint64]$a -bxor [uint64]$b) -band 4294967295) }

function Write-U16BE {
    param([byte[]]$Buf, [int]$Offset, [uint32]$Value)
    $Buf[$Offset]     = [byte](($Value -shr 8) -band 0xFF)
    $Buf[$Offset + 1] = [byte]($Value -band 0xFF)
}
function Write-U32BE {
    param([byte[]]$Buf, [int]$Offset, [uint32]$Value)
    $Buf[$Offset]     = [byte](($Value -shr 24) -band 0xFF)
    $Buf[$Offset + 1] = [byte](($Value -shr 16) -band 0xFF)
    $Buf[$Offset + 2] = [byte](($Value -shr 8) -band 0xFF)
    $Buf[$Offset + 3] = [byte]($Value -band 0xFF)
}

# =============================================================================
#  CRC32 (IEEE, reflected, poly 0xEDB88320) — same table as the JS sender
# =============================================================================
$script:CrcTable = $null
function Initialize-Crc32 {
    if ($script:CrcTable) { return }
    $t = New-Object 'uint32[]' 256
    for ($n = 0; $n -lt 256; $n++) {
        [uint64]$c = [uint64]$n
        for ($k = 0; $k -lt 8; $k++) {
            if (($c -band 1) -ne 0) { $c = [uint64](3988292384 -bxor ($c -shr 1)) }   # 0xEDB88320
            else                    { $c = [uint64]($c -shr 1) }
        }
        $t[$n] = [uint32]($c -band 0xFFFFFFFF)
    }
    $script:CrcTable = $t
}

function Get-Crc32 {
    param([byte[]]$Bytes, [int]$Start = 0, [int]$End = -1)
    Initialize-Crc32
    if ($End -lt 0) { $End = $Bytes.Length }
    [uint64]$crc = 4294967295
    for ($i = $Start; $i -lt $End; $i++) {
        $idx = [int](($crc -bxor [uint64]$Bytes[$i]) -band 255)
        $crc = [uint64]($script:CrcTable[$idx] -bxor ($crc -shr 8))
    }
    return [uint32](($crc -bxor [uint64]4294967295) -band 4294967295)
}

# =============================================================================
#  Deterministic fountain code — byte-identical to detLog/buildDegreeCDF/
#  pktRandom/indicesForPacket in sender.html and receiver.html.
#  Only IEEE-754 correctly-rounded operations are used, so the receiver derives
#  exactly the same block indices for a given (sessionId, packetId, k).
# =============================================================================
function Get-DetLog {
    param([double]$x)
    $e = 0
    while ($x -ge 2) { $x /= 2; $e++ }
    while ($x -lt 1) { $x *= 2; $e-- }
    $t = ($x - 1) / ($x + 1)
    $t2 = $t * $t
    $sum = 0.0
    $term = $t
    for ($n = 1; $n -le 19; $n += 2) {
        $sum += $term / $n
        $term *= $t2
    }
    return 2 * $sum + $e * 0.6931471805599453
}

function Get-DegreeCdf {
    param([int]$K)
    if ($K -lt 1) { $K = 1 }

    $mu = New-Object 'double[]' ($K + 1)
    $mu[1] = 1.0 / $K
    for ($i = 2; $i -le $K; $i++) { $mu[$i] = 1.0 / ([double]$i * ($i - 1)) }

    $S = 0.1 * (Get-DetLog ($K / 0.05)) * [Math]::Sqrt([double]$K)
    if ($S -lt 1) { $S = 1.0 }
    $kS = [int][Math]::Floor($K / $S)
    if ($kS -ge 1) {
        for ($i = 1; $i -lt $kS -and $i -le $K; $i++) { $mu[$i] += $S / ([double]$K * $i) }
        if ($kS -le $K) { $mu[$kS] += $S * (Get-DetLog ($S / 0.05)) / $K }
    }

    $beta = 0.0
    for ($i = 1; $i -le $K; $i++) { $beta += $mu[$i] }
    for ($i = 1; $i -le $K; $i++) { $mu[$i] = 0.7 * $mu[$i] / $beta }

    $dDense = [int][Math]::Min([double]$K, [Math]::Min(512.0, [Math]::Max(8.0, [Math]::Floor($K / 2.0))))
    $mu[$dDense] += 0.3

    $cdf = New-Object 'double[]' ($K + 1)
    $acc = 0.0
    for ($i = 1; $i -le $K; $i++) { $acc += $mu[$i]; $cdf[$i] = $acc }
    $cdf[$K] = 1.0
    return , $cdf
}

function New-PktRng {
    param([uint32]$SessionId, [uint32]$PacketId)
    # x = (sessionId ^ imul(packetId + 0x9E3779B9, 0x85EBCA6B)) >>> 0
    $t = [uint32](([uint64]$PacketId + 2654435769) % 4294967296)      # 0x9E3779B9
    $x = Xor32 $SessionId (Mul32 $t 2246822507)                       # 0x85EBCA6B
    $x = Xor32 $x (Shr32 $x 16)
    $x = Mul32 $x 73244475                                            # 0x045D9F3B
    $x = Xor32 $x (Shr32 $x 16)
    if ($x -eq 0) { $x = [uint32]521288629 }                          # 0x1F123BB5
    return @{ X = $x }
}

function Get-RngNext {
    param([hashtable]$State)
    $x = $State.X
    $x = Xor32 $x (Shl32 $x 13)
    $x = Xor32 $x (Shr32 $x 17)
    $x = Xor32 $x (Shl32 $x 5)
    $State.X = $x
    return $x
}

function Get-IndicesForPacket {
    param([uint32]$SessionId, [uint32]$PacketId, [int]$K, [double[]]$Cdf)
    if ($PacketId -lt $K) { return , @([int]$PacketId) }   # systematic pass: block i verbatim

    $rng = New-PktRng $SessionId $PacketId
    $u = (Get-RngNext $rng) / 4294967296.0

    $lo = 1; $hi = $K
    while ($lo -lt $hi) {
        $mid = [int][Math]::Floor(($lo + $hi) / 2)
        if ($Cdf[$mid] -lt $u) { $lo = $mid + 1 } else { $hi = $mid }
    }
    $d = [int][Math]::Min($lo, $K)

    $set = New-Object 'System.Collections.Generic.HashSet[int]'
    $guard = 0
    $cap = $d * 20 + 1000
    while ($set.Count -lt $d -and $guard -lt $cap) {
        $guard++
        [void]$set.Add([int]((Get-RngNext $rng) % [uint32]$K))
    }
    if ($set.Count -lt $d) {
        for ($i = 0; $i -lt $K -and $set.Count -lt $d; $i++) { [void]$set.Add($i) }
    }
    return , ([int[]]@($set))
}

# =============================================================================
#  Compression / transfer preparation
# =============================================================================
function Compress-DeflateRaw {
    param([byte[]]$Data)
    $ms = New-Object System.IO.MemoryStream
    $ds = New-Object System.IO.Compression.DeflateStream($ms, [System.IO.Compression.CompressionMode]::Compress, $true)
    try { $ds.Write($Data, 0, $Data.Length) } finally { $ds.Dispose() }
    $out = $ms.ToArray()
    $ms.Dispose()
    # .NET emits NOTHING for empty input, but the receiver's pako.inflateRaw
    # throws on a zero-length stream. The browser sender's CompressionStream
    # emits the canonical 2-byte empty block (BFINAL=1, fixed Huffman, EOB),
    # so match that for zero-byte files.
    if ($out.Length -eq 0) { return , ([byte[]](0x03, 0x00)) }
    return , $out
}

function New-RandomSessionId {
    $b = New-Object byte[] 4
    $rng = New-Object System.Security.Cryptography.RNGCryptoServiceProvider
    try { $rng.GetBytes($b) } finally { $rng.Dispose() }
    return [uint32]([BitConverter]::ToUInt32($b, 0))
}

function New-TransferObject {
    param(
        [string]$FileName,
        [uint32]$OriginalSize,
        [byte[]]$Compressed,
        [string]$PresetName,
        [uint32]$SessionId
    )

    $p = $script:Presets[$PresetName]
    $blockSize = [int]$p.BlockSize
    $paddedSize = [int]([Math]::Ceiling($blockSize / 4.0) * 4)
    $k = [int][Math]::Max(1, [Math]::Ceiling($Compressed.Length / [double]$blockSize))
    if ($k -gt 65535) {
        throw ("File too large for this preset: {0} blocks > 65535. Split the file into smaller parts." -f $k)
    }

    $blockInts = New-Object 'System.Numerics.BigInteger[]' $k
    for ($i = 0; $i -lt $k; $i++) {
        $padded = New-Object byte[] ($paddedSize + 1)      # +1 zero byte keeps BigInteger positive
        $start = $i * $blockSize
        $n = [Math]::Min($blockSize, $Compressed.Length - $start)
        if ($n -gt 0) { [Array]::Copy($Compressed, $start, $padded, 0, $n) }
        $blockInts[$i] = [System.Numerics.BigInteger]::new($padded)
    }

    return [pscustomobject]@{
        FileName       = $FileName
        OriginalSize   = $OriginalSize
        SourceBytes    = $null
        Compressed     = $Compressed
        CompressedSize = [uint32]$Compressed.Length
        CrcCompressed  = [uint32](Get-Crc32 $Compressed)
        BlockSize      = $blockSize
        PaddedSize     = $paddedSize
        K              = $k
        Blocks         = $blockInts
        Cdf            = Get-DegreeCdf $k
        SessionId      = [uint32]$SessionId
        PresetName     = $PresetName
        Version        = [int]$p.Version
    }
}

function New-Transfer {
    param(
        [string]$FilePath,
        [string]$PresetName,
        [byte[]]$SourceBytes,
        [uint32]$SessionId
    )

    if ($PSBoundParameters.ContainsKey('SourceBytes') -and $null -ne $SourceBytes) {
        $bytes = $SourceBytes
        $name = if ($FilePath) { [IO.Path]::GetFileName($FilePath) } else { 'transfer.bin' }
    }
    else {
        $bytes = [IO.File]::ReadAllBytes($FilePath)
        $name = [IO.Path]::GetFileName($FilePath)
    }

    if (-not $PSBoundParameters.ContainsKey('SessionId') -or $SessionId -eq 0) { $SessionId = New-RandomSessionId }

    $T = New-TransferObject -FileName $name -OriginalSize ([uint32]$bytes.Length) `
        -Compressed (Compress-DeflateRaw $bytes) -PresetName $PresetName -SessionId $SessionId
    $T.SourceBytes = $bytes
    return $T
}

# =============================================================================
#  Packet builders
# =============================================================================
function New-HeaderPacket {
    param($T)
    $nameBytes = [Text.Encoding]::UTF8.GetBytes($T.FileName)
    if ($nameBytes.Length -gt 255) { $nameBytes = $nameBytes[0..254] }

    $len = 1 + 4 + 1 + $nameBytes.Length + 4 + 4 + 2 + 2 + 4 + 4
    $buf = New-Object byte[] $len
    $o = 0
    $buf[$o++] = 0x00
    Write-U32BE $buf $o $T.SessionId;            $o += 4
    $buf[$o++] = [byte]$nameBytes.Length
    [Array]::Copy($nameBytes, 0, $buf, $o, $nameBytes.Length); $o += $nameBytes.Length
    Write-U32BE $buf $o $T.OriginalSize;         $o += 4
    Write-U32BE $buf $o $T.CompressedSize;       $o += 4
    Write-U16BE $buf $o $T.BlockSize;            $o += 2
    Write-U16BE $buf $o ([uint32]$T.K);          $o += 2
    Write-U32BE $buf $o $T.CrcCompressed;        $o += 4
    Write-U32BE $buf $o (Get-Crc32 $buf 0 $o)
    return , $buf
}

function Get-XorPayload {
    param($T, [int[]]$Indices)
    $acc = [System.Numerics.BigInteger]::Zero
    foreach ($i in $Indices) { $acc = $acc -bxor $T.Blocks[$i] }
    $raw = $acc.ToByteArray()
    $out = New-Object byte[] $T.BlockSize
    $n = [Math]::Min($T.BlockSize, $raw.Length)
    if ($n -gt 0) { [Array]::Copy($raw, 0, $out, 0, $n) }
    return , $out
}

function New-DataPacket {
    param($T, [uint32]$PacketId)
    $indices = Get-IndicesForPacket $T.SessionId $PacketId $T.K $T.Cdf
    $payload = Get-XorPayload $T $indices

    $len = $script:DataOverhead + $T.BlockSize
    $buf = New-Object byte[] $len
    $buf[0] = 0x02
    Write-U32BE $buf 1  $T.SessionId
    Write-U32BE $buf 5  $PacketId
    Write-U16BE $buf 9  ([uint32]$T.K)
    Write-U16BE $buf 11 ([uint32]$T.BlockSize)
    Write-U32BE $buf 13 $T.CompressedSize
    Write-U32BE $buf 17 $T.OriginalSize
    Write-U32BE $buf 21 $T.CrcCompressed
    [Array]::Copy($payload, 0, $buf, 25, $T.BlockSize)
    Write-U32BE $buf ($len - 4) (Get-Crc32 $buf 0 ($len - 4))
    return , $buf
}

function Get-NextPacket {
    param($T, [ref]$Scheduler, [int]$FrameIndex)
    if ($FrameIndex -lt 2 -or ($FrameIndex % $script:HeaderEvery) -eq 0) {
        $Scheduler.Value.HeaderFrames++
        return [pscustomobject]@{ Bytes = (New-HeaderPacket $T); IsHeader = $true; PacketId = -1 }
    }
    if ($Scheduler.Value.NextSystematic -lt $T.K) {
        $packetId = [uint32]$Scheduler.Value.NextSystematic
        $Scheduler.Value.NextSystematic++
    }
    else {
        $packetId = [uint32]$Scheduler.Value.NextFountain
        $Scheduler.Value.NextFountain++
    }
    $Scheduler.Value.PacketsSent++
    return [pscustomobject]@{ Bytes = (New-DataPacket $T $packetId); IsHeader = $false; PacketId = $packetId }
}

# =============================================================================
#  QR rendering (ZXing.Net -> 1px/module bitmap -> nearest-neighbour scale)
# =============================================================================
function New-QrBitmap1x {
    param($Matrix, [int]$QuietZone = 4)
    # $Matrix is a ZXing ByteMatrix (1 = dark). The quiet zone is added here so
    # the bitmap is exactly what the browser sender draws: modules + 4 modules
    # of margin, one pixel per module.
    $n = $Matrix.Width
    $mods = $n + 2 * $QuietZone
    $bmp = New-Object System.Drawing.Bitmap($mods, $mods, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $rect = New-Object System.Drawing.Rectangle(0, 0, $mods, $mods)
    $bd = $bmp.LockBits($rect, [System.Drawing.Imaging.ImageLockMode]::WriteOnly, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    try {
        $stride = $bd.Stride
        $buf = New-Object byte[] ($stride * $mods)
        for ($i = 0; $i -lt $buf.Length; $i++) { $buf[$i] = 255 }
        for ($y = 0; $y -lt $n; $y++) {
            $rowBase = ($y + $QuietZone) * $stride + $QuietZone * 4
            for ($x = 0; $x -lt $n; $x++) {
                if ($Matrix[$x, $y] -eq 1) {
                    $o = $rowBase + $x * 4
                    $buf[$o] = 0; $buf[$o + 1] = 0; $buf[$o + 2] = 0; $buf[$o + 3] = 255
                }
            }
        }
        [System.Runtime.InteropServices.Marshal]::Copy($buf, 0, $bd.Scan0, $buf.Length)
    }
    finally { $bmp.UnlockBits($bd) }
    return $bmp
}

function New-ScaledBitmap {
    param([System.Drawing.Bitmap]$Source, [int]$Scale)
    $w = $Source.Width * $Scale
    $bmp = New-Object System.Drawing.Bitmap($w, $w, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    try {
        $g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::NearestNeighbor
        $g.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::Half
        $g.DrawImage($Source, 0, 0, $w, $w)
    }
    finally { $g.Dispose() }
    return $bmp
}

function Get-QrCode {
    param($QrLib, $T, [byte[]]$Packet)
    # Binary payload -> ISO-8859-1 string (1 byte per char), exactly like the JS
    # sender's overridden stringToBytes. ZXing defaults to ISO-8859-1 byte mode,
    # so the symbol carries the raw bytes verbatim. No CHARACTER_SET hint: that
    # would add a 12-bit ECI header and cost one byte of capacity.
    $latin1 = [Text.Encoding]::GetEncoding(28591).GetString($Packet)
    $ecc = if ($T.PresetName -eq 'robust') { $QrLib.EccM } else { $QrLib.EccL }
    $hints = New-Object 'System.Collections.Generic.Dictionary[ZXing.EncodeHintType,object]'
    $hints[[ZXing.EncodeHintType]::ERROR_CORRECTION] = $ecc
    $hints[[ZXing.EncodeHintType]::QR_VERSION] = [int]$T.Version
    return [ZXing.QrCode.Internal.Encoder]::encode($latin1, $ecc, $hints)
}

function ConvertTo-QrBitmap {
    param($QrLib, $T, [byte[]]$Packet, [int]$Scale)
    $qr = Get-QrCode $QrLib $T $Packet
    $small = New-QrBitmap1x $qr.Matrix 4
    try { return (New-ScaledBitmap $small $Scale) }
    finally { $small.Dispose() }
}

function Read-QrBitmapBytes {
    # Decode oracle for -SelfTest only (a clean, axis-aligned rendering, hence
    # PURE_BARCODE). Returns $null when the bitmap cannot be decoded.
    param([System.Drawing.Bitmap]$Bitmap)
    $reader = New-Object ZXing.BarcodeReader
    $reader.Options.TryHarder = $true
    $reader.Options.Hints[[ZXing.DecodeHintType]::PURE_BARCODE] = $true
    $res = $reader.Decode($Bitmap)
    if (-not $res) { return $null }
    $segments = @($res.ResultMetadata[[ZXing.ResultMetadataType]::BYTE_SEGMENTS] | Where-Object { $null -ne $_ })
    $bytes = New-Object System.Collections.Generic.List[byte]
    foreach ($segment in $segments) { $bytes.AddRange($segment) }
    return , $bytes.ToArray()
}

# =============================================================================
#  Headless runner (also used for conformance testing / packet dumping)
# =============================================================================
function Invoke-Headless {
    param($T, [int]$FrameCount, [string]$DumpDir, [int]$IntervalMs, [string]$QrDir, [int]$QrScale = 4, $QrLib)

    $scheduler = @{ NextSystematic = 0; NextFountain = $T.K; PacketsSent = 0; HeaderFrames = 0 }
    if ($DumpDir) {
        if (-not (Test-Path -LiteralPath $DumpDir)) { New-Item -ItemType Directory -Path $DumpDir -Force | Out-Null }
    }
    if ($QrDir) {
        if (-not (Test-Path -LiteralPath $QrDir)) { New-Item -ItemType Directory -Path $QrDir -Force | Out-Null }
    }

    Write-Host ("File      : {0} ({1:N0} B original, {2:N0} B compressed, {3} blocks of {4} B)" -f `
        $T.FileName, $T.OriginalSize, $T.CompressedSize, $T.K, $T.BlockSize)
    Write-Host ("Session   : 0x{0:X8}   preset={1} (v{2})   interval={3} ms" -f $T.SessionId, $T.PresetName, $T.Version, $IntervalMs)

    $sw = [Diagnostics.Stopwatch]::StartNew()
    $i = 0
    $limit = if ($FrameCount -gt 0) { $FrameCount } else { [int]::MaxValue }
    while ($i -lt $limit) {
        $pkt = Get-NextPacket $T ([ref]$scheduler) $i
        if ($DumpDir) {
            $name = if ($pkt.IsHeader) { '{0:D6}_header.bin' -f $i } else { '{0:D6}_pid{1:D6}.bin' -f $i, $pkt.PacketId }
            [IO.File]::WriteAllBytes((Join-Path $DumpDir $name), $pkt.Bytes)
        }
        if ($QrDir) {
            $bmp = ConvertTo-QrBitmap $QrLib $T $pkt.Bytes $QrScale
            try {
                $name = if ($pkt.IsHeader) { '{0:D6}_header.png' -f $i } else { '{0:D6}_pid{1:D6}.png' -f $i, $pkt.PacketId }
                $bmp.Save((Join-Path $QrDir $name), [System.Drawing.Imaging.ImageFormat]::Png)
            }
            finally { $bmp.Dispose() }
        }
        $i++
        if ($FrameCount -eq 0 -and ($i % 50) -eq 0) { Write-Host ("  {0} frames, {1} data packets" -f $i, $scheduler.PacketsSent) }
    }
    $sw.Stop()

    $elapsed = [Math]::Max(0.001, $sw.Elapsed.TotalSeconds)
    Write-Host ("Frames    : {0}  (data packets {1}, header frames {2})" -f $i, $scheduler.PacketsSent, $scheduler.HeaderFrames)
    Write-Host ("Elapsed   : {0:N2} s   ({1:N1} frames/s, {2:N1} KB/s if display-bound)" -f `
        $elapsed, ($i / $elapsed), (($scheduler.PacketsSent * ($T.BlockSize + 29)) / $elapsed / 1024))
}

# =============================================================================
#  Self test — vectors captured from sender.html (protocol v2)
# =============================================================================
function Invoke-SelfTest {
    param($QrLib)

    $script:SelfTestFailures = 0
    function Check([string]$Name, $Actual, $Expected) {
        if ("$Actual" -eq "$Expected") {
            Write-Host ("  PASS  {0}" -f $Name) -ForegroundColor Green
        }
        else {
            Write-Host ("  FAIL  {0}`n        expected: {1}`n        actual  : {2}" -f $Name, $Expected, $Actual) -ForegroundColor Red
            $script:SelfTestFailures++
        }
    }
    function Check-Double([string]$Name, [double]$Actual, [string]$ExpectedText) {
        $expected = [double]::Parse($ExpectedText, [Globalization.CultureInfo]::InvariantCulture)
        $bitsOk = [BitConverter]::DoubleToInt64Bits($Actual) -eq [BitConverter]::DoubleToInt64Bits($expected)
        Check $Name $bitsOk $true
        if (-not $bitsOk) { Write-Host ("        actual bits {0:X16} vs {1:X16}" -f [BitConverter]::DoubleToInt64Bits($Actual), [BitConverter]::DoubleToInt64Bits($expected)) -ForegroundColor DarkYellow }
    }

    Write-Host 'CRC32' -ForegroundColor Cyan
    Check 'crc32(00 01 02 03 FA..FF 41 42 43)' (Get-Crc32 ([byte[]](0, 1, 2, 3, 250, 251, 252, 253, 254, 255, 65, 66, 67))) 4181860810
    $ab = New-Object byte[] 1003
    for ($i = 0; $i -lt $ab.Length; $i++) { $ab[$i] = 0xAB }
    Check 'crc32(1003 x 0xAB)' (Get-Crc32 $ab) 4231937091

    Write-Host 'detLog' -ForegroundColor Cyan
    Check-Double 'detLog(0.5)'   (Get-DetLog 0.5)   '-0.6931471805599453'
    Check-Double 'detLog(1)'     (Get-DetLog 1)     '0'
    Check-Double 'detLog(10)'    (Get-DetLog 10)    '2.3025850929940455'
    Check-Double 'detLog(1000)'  (Get-DetLog 1000)  '6.907755278977026'
    Check-Double 'detLog(20000)' (Get-DetLog 20000) '9.903487552536127'

    Write-Host 'degree CDF (k=10)' -ForegroundColor Cyan
    $cdf = Get-DegreeCdf 10
    $expectedCdf = @(
        0.0, 0.096664545059617898, 0.30758119691877550, 0.38797586136956624, 0.43321775051049738,
        0.66387013792681149, 0.67591342528454101, 0.68451577339720493, 0.99096753448170283,
        0.99598557088075679, 1.0
    )
    $cdfOk = $true
    for ($i = 0; $i -le 10; $i++) {
        if ([BitConverter]::DoubleToInt64Bits($cdf[$i]) -ne [BitConverter]::DoubleToInt64Bits([double]$expectedCdf[$i])) { $cdfOk = $false }
    }
    Check 'cdf[0..10] bit-identical' $cdfOk $true

    Write-Host 'PRNG stream (session 0x11223344, packetId 100..103)' -ForegroundColor Cyan
    $expectedRng = @(
        '3843905120,3053404296,3760431519',
        '956112315,4060885982,4203672901',
        '2097288939,3291629956,760442789',
        '3091230968,2109362487,3288987097'
    )
    for ($i = 0; $i -lt 4; $i++) {
        $r = New-PktRng ([uint32]0x11223344) ([uint32](100 + $i))
        $vals = @((Get-RngNext $r), (Get-RngNext $r), (Get-RngNext $r)) -join ','
        Check ("rng[{0}]" -f (100 + $i)) $vals $expectedRng[$i]
    }

    Write-Host 'packet bytes (synthetic 3000 B payload -> k=4, v22/ECC-L)' -ForegroundColor Cyan
    $comp = New-Object byte[] 3000
    for ($i = 0; $i -lt 3000; $i++) {
        $comp[$i] = [byte]((($i * 37) + ([Math]::Floor($i / 8) * 11) + 7) -band 0xFF)
    }
    $T = New-TransferObject -FileName 't.bin' -OriginalSize ([uint32]4321) -Compressed $comp `
        -PresetName 'balanced' -SessionId ([uint32]0x11223344)

    $sha = [Security.Cryptography.SHA256]::Create()
    function Get-Sha([byte[]]$b) { ([BitConverter]::ToString($sha.ComputeHash($b)) -replace '-', '').ToLowerInvariant() }

    Check 'k for 3000 B / 974 B blocks' $T.K 4
    Check 'header hex' ([BitConverter]::ToString((New-HeaderPacket $T)) -replace '-', '').ToLowerInvariant() `
        '001122334405742e62696e000010e100000bb803ce0004a63183bf14d54ce7'
    Check 'header sha256' (Get-Sha (New-HeaderPacket $T)) '9044432ef23ded8142eb1133b7126054439617295d5293e515988d4b4c16cbcc'
    Check 'packet 0 sha256'   (Get-Sha (New-DataPacket $T 0))   'cfccac81e278d1137cdf0302344469e4083041801e2862a2900990cfdd3f567f'
    Check 'packet 1 sha256'   (Get-Sha (New-DataPacket $T 1))   'b56598cd06e758b38273b3bf18b28bafb3ec9822af59a0a8129ed028facb96e8'
    Check 'packet 3 sha256'   (Get-Sha (New-DataPacket $T 3))   '903070e30144df4c4cf64d459d344a62b7b7eca2e43ff39cd9882dec8d826121'
    Check 'packet 4 sha256'   (Get-Sha (New-DataPacket $T 4))   '4e9bc008d5ad3279f00352f4493f61477f421b927306f00943de5a6f445d6af0'
    Check 'packet 5 sha256'   (Get-Sha (New-DataPacket $T 5))   'fa937f64f4b91c904381b632a808f90b1a878f6a91b85109ade5fcb18ecf4916'
    Check 'packet 100 sha256' (Get-Sha (New-DataPacket $T 100)) '6ce17bd9727abe5cf4446c6f9e6ab5f6a1ce26d188ccbcbfa40f8f4561adefff'
    $sha.Dispose()

    Write-Host 'deflate round-trip' -ForegroundColor Cyan
    $sample = [Text.Encoding]::UTF8.GetBytes(('The quick brown fox jumps over the lazy dog. ' * 200))
    $def = Compress-DeflateRaw $sample
    $ms = New-Object IO.MemoryStream($def, $false)
    $inf = New-Object IO.Compression.DeflateStream($ms, [IO.Compression.CompressionMode]::Decompress)
    $back = New-Object IO.MemoryStream
    $inf.CopyTo($back); $inf.Dispose(); $ms.Dispose()
    Check 'deflate round-trip' ($back.ToArray().Length -eq $sample.Length) $true
    Check 'empty input -> 03 00 (pako-compatible)' ([BitConverter]::ToString((Compress-DeflateRaw ([byte[]]@())))) '03-00'

    Write-Host 'QR encode/decode round-trip (byte mode, forced version)' -ForegroundColor Cyan
    $pkt = New-HeaderPacket $T
    $qr = ConvertTo-QrBitmap $QrLib $T $pkt 2
    Check 'QR bitmap size (v22 -> 113 modules x2)' ("{0}x{1}" -f $qr.Width, $qr.Height) '226x226'
    Check 'QR round-trip (header packet)' ([BitConverter]::ToString((Read-QrBitmapBytes $qr))) ([BitConverter]::ToString($pkt))
    $qr.Dispose()

    # Regression: QRCoder 1.4.3 zeroed the last data codewords for zero-heavy
    # payloads, which silently broke the CRC of e.g. the empty-file packet. Any
    # encoder swap must keep these two byte-exact.
    foreach ($presetName in 'balanced', 'robust') {
        $zeroT = New-Transfer -SourceBytes ([byte[]]@()) -PresetName $presetName -SessionId ([uint32]16164790)
        $zeroPkt = New-DataPacket $zeroT 0
        $bmp = ConvertTo-QrBitmap $QrLib $zeroT $zeroPkt 4
        try {
            $back = Read-QrBitmapBytes $bmp
            Check ("QR round-trip (zero-tail packet, {0}, {1} B)" -f $presetName, $zeroPkt.Length) ([BitConverter]::ToString($back)) ([BitConverter]::ToString($zeroPkt))
        }
        finally { $bmp.Dispose() }
    }

    Write-Host ''
    if ($script:SelfTestFailures -eq 0) {
        Write-Host 'ALL TESTS PASSED' -ForegroundColor Green
    }
    else {
        Write-Host ("{0} TEST(S) FAILED" -f $script:SelfTestFailures) -ForegroundColor Red
    }
    return ($script:SelfTestFailures -eq 0)
}

