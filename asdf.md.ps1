                    # re-prepare from the cached bytes (new session id, like the JS sender)
                    $script:G.T = New-Transfer -FilePath $script:G.T.FileName -PresetName $newPreset -SourceBytes $script:G.T.SourceBytes
                    $script:G.Scheduler = @{ NextSystematic = 0; NextFountain = $script:G.T.K; PacketsSent = 0; HeaderFrames = 0 }
                    Add-Log ('Preset → {0}: k={1}, session 0x{2:X8}' -f $newPreset, $script:G.T.K, $script:G.T.SessionId)
                    Update-Stats
                }
            }
        })

    $cmbInt.Add_SelectedIndexChanged({
            $map = @(50, 66, 100, 150, 250)
            $script:G.IntervalMs = $map[$cmbInt.SelectedIndex]
            $script:G.Timer.Interval = $script:G.IntervalMs
        })

    $toggleFullscreen = {
        if (-not $script:G.Fullscreen) {
            $script:G.PrevBounds = $form.Bounds
            $script:G.PrevStyle = $form.FormBorderStyle
            $form.FormBorderStyle = 'None'
            $form.WindowState = 'Maximized'
            $log.Visible = $false
            $status.Visible = $false
            $top.Visible = $false
            $beacon.Height = 18
            $script:G.Fullscreen = $true
        }
        else {
            $form.FormBorderStyle = $script:G.PrevStyle
            $form.WindowState = 'Normal'
            $form.Bounds = $script:G.PrevBounds
            $log.Visible = $true
            $status.Visible = $true
            $top.Visible = $true
            $script:G.Fullscreen = $false
        }
    }

    $btnFull.Add_Click($toggleFullscreen)
    # While idle the stage shows a notice that must be re-drawn at the new
    # size; while broadcasting the next timer tick re-renders anyway.
    $form.Add_Resize({
            if ($script:G.Running -or -not $script:G.T) { return }
            $old = $script:G.Image
            $script:G.Image = New-IdleBitmap
            $picture.Image = $script:G.Image
            if ($old) { $old.Dispose() }
        })

    $form.Add_KeyDown({
            param($s, $e)
            if ($e.KeyCode -eq 'F11') { & $toggleFullscreen; $e.Handled = $true }
            elseif ($e.KeyCode -eq 'Escape') {
                if ($script:G.Fullscreen) { & $toggleFullscreen } else { $form.Close() }
            }
            elseif ($e.KeyCode -eq 'Space') {
                if ($script:G.Running) { Stop-Broadcast } else { Start-Broadcast }
                $e.Handled = $true
            }
        })

    $form.Add_DragEnter({ param($s, $e) if ($e.Data.GetDataPresent('FileDrop')) { $e.Effect = 'Copy' } })
    $form.Add_DragDrop({
            param($s, $e)
            $files = $e.Data.GetData('FileDrop')
            if ($files -and $files.Count -gt 0) { Load-File $files[0] }
        })

    $form.Add_FormClosing({ Stop-Broadcast })

    $form.Add_Shown({
            Add-Log 'Ready. Choose a file (or drop one on the window). Space = start/stop, F11 = fullscreen, Esc = close.'
            if ($InitialPath) { Load-File $InitialPath }
        })

    [void]$form.ShowDialog()
}

