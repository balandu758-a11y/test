    function Render-Frame([byte[]]$Packet) {
        # The QR is built once at 1 px/module (which also tells us the module
        # count, quiet zone included) and then nearest-neighbour scaled to the
        # largest integer fit inside the stage — same rendering rule as the
        # browser sender, so module edges stay pixel-exact.
        $availW = [Math]::Max(64, $picture.ClientSize.Width)
        $availH = [Math]::Max(64, $picture.ClientSize.Height)
        $probe = ConvertTo-QrBitmap $QrLib $script:G.T $Packet 1
        $m = $probe.Width
        $scale = [int][Math]::Max(1, [Math]::Min([Math]::Floor($availW / $m), [Math]::Floor($availH / $m)))
        $next = if ($scale -gt 1) { New-ScaledBitmap $probe $scale } else { $probe }
        if ($next -ne $probe) { $probe.Dispose() }
        $old = $script:G.Image
        $picture.Image = $next
        $script:G.Image = $next
        if ($old) { $old.Dispose() }
        $script:G.BeaconPhase = -not $script:G.BeaconPhase
        $beacon.BackColor = if ($script:G.BeaconPhase) { [System.Drawing.Color]::Black } else { [System.Drawing.Color]::White }
    }

    $tick = {
        if (-not $script:G.Running) { return }
        try {
            $pkt = Get-NextPacket $script:G.T ([ref]$script:G.Scheduler) $script:G.FrameIndex
            Render-Frame $pkt.Bytes
            $script:G.FrameIndex++
            $script:G.FramesShown++
            if (($script:G.FrameIndex % 10) -eq 0) { Update-Stats }
        }
        catch {
            Add-Log ('Frame build error: ' + $_.Exception.Message)
        }
    }

