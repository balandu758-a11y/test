    }

    # A stopped (or fresh) sender must not leave a QR frozen on screen: the
    # receiver would keep re-reading it as a live packet. The browser sender
    # blanks the stage with a notice, and so do we.
    function New-IdleBitmap {
        $w = [Math]::Max(64, $picture.ClientSize.Width)
        $h = [Math]::Max(64, $picture.ClientSize.Height)
        $bmp = New-Object System.Drawing.Bitmap($w, $h, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
        $g = [System.Drawing.Graphics]::FromImage($bmp)
        $font = New-Object System.Drawing.Font('Segoe UI', 15)
        try {
            $g.Clear([System.Drawing.Color]::White)
            $fmt = New-Object System.Drawing.StringFormat
            $fmt.Alignment = [System.Drawing.StringAlignment]::Center
            $fmt.LineAlignment = [System.Drawing.StringAlignment]::Center
            $rect = New-Object System.Drawing.RectangleF(0, 0, $w, $h)
            $g.DrawString('stopped — no data on screen', $font, [System.Drawing.Brushes]::Gray, $rect, $fmt)
        }
        finally {
            $font.Dispose()
            $g.Dispose()
        }
        return $bmp
    }

    function Stop-Broadcast {
        $wasRunning = $script:G.Running
        $script:G.Running = $false
        $script:G.Timer.Stop()
        $old = $script:G.Image
        $picture.Image = New-IdleBitmap
        $script:G.Image = $picture.Image
        if ($old) { $old.Dispose() }
        $beacon.BackColor = [System.Drawing.Color]::White
        if ($wasRunning -and $script:G.Scheduler) {
            Add-Log ('Stopped. {0} frames shown, {1} data packets sent.' -f $script:G.FramesShown, $script:G.Scheduler.PacketsSent)
        }
        Set-Buttons
    }

